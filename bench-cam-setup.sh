#!/usr/bin/env bash
# bench-cam-setup.sh — stream a USB document camera from this Ubuntu box over the LAN
# using MediaMTX (RTSP + WebRTC) with ffmpeg doing the capture/encode.
#
# Run on the Ubuntu bench PC:   sudo bash bench-cam-setup.sh
# Re-run any time after editing the settings below, or after plugging in the camera; it's idempotent.
# Works without a camera attached: installs everything and writes a config with no capture command.
#
# Viewing (from any computer on the LAN; <bench-pc> is the hostname of the machine running this):
#   Browser (WebRTC, low latency):  http://<bench-pc>.local:8889/bench
#   VLC / ffmpeg / OpenCV (RTSP):   rtsp://<bench-pc>.local:8554/bench
#   One frame for an AI pipeline:   ffmpeg -rtsp_transport tcp -i rtsp://<bench-pc>.local:8554/bench -frames:v 1 -y bench.jpg

set -euo pipefail

# ---------------- settings ----------------
STREAM_NAME="bench"
WIDTH=1920            # live-view size; try 2560x1440, or 3264x2448 at FPS=15 for max detail
HEIGHT=1080
FPS=30
BITRATE="8M"
CAMERA=""             # leave empty to auto-pick the first USB camera; or set /dev/v4l/by-id/...-video-index0
MEDIAMTX_VERSION=""   # leave empty for the latest release
# ------------------------------------------

[[ $EUID -eq 0 ]] || { echo "Run with sudo."; exit 1; }

echo "==> Installing packages"
apt-get update -qq
apt-get install -y -qq ffmpeg v4l-utils curl tar >/dev/null

echo "==> Finding the camera"
if [[ -z "$CAMERA" ]]; then
  CAMERA=$(ls /dev/v4l/by-id/*-video-index0 2>/dev/null | head -n1 || true)
fi
NO_CAM=0
if [[ -n "$CAMERA" && -e "$CAMERA" ]]; then
  echo "    Using $CAMERA"
  echo "    MJPEG modes it offers:"
  v4l2-ctl -d "$CAMERA" --list-formats-ext 2>/dev/null | awk '/MJPG/{f=1} f&&/Size/{print "      "$3} /YUYV/{f=0}' | sort -u | head -n 12 || true
else
  NO_CAM=1
  echo "    No USB camera found - installing everything else. Plug it in, then re-run this script."
fi

echo "==> Picking an encoder"
if ffmpeg -hide_banner -encoders 2>/dev/null | grep -q h264_nvenc && command -v nvidia-smi >/dev/null && nvidia-smi >/dev/null 2>&1; then
  ENC="-c:v h264_nvenc -preset p1 -tune ll -profile:v baseline -bf 0"
  echo "    NVIDIA GPU found: h264_nvenc"
else
  ENC="-c:v libx264 -preset ultrafast -tune zerolatency -profile:v baseline"
  echo "    Using CPU encoder: libx264"
fi

echo "==> Installing MediaMTX"
case "$(uname -m)" in
  x86_64)  ARCH=amd64 ;;
  aarch64) ARCH=arm64 ;;
  *) echo "Unsupported arch $(uname -m)"; exit 1 ;;
esac
if [[ -z "$MEDIAMTX_VERSION" ]]; then
  RELEASE_JSON=$(curl -fsSL https://api.github.com/repos/bluenviron/mediamtx/releases/latest)
  MEDIAMTX_VERSION=$(grep -m1 '"tag_name"' <<<"$RELEASE_JSON" | cut -d'"' -f4)
  [[ -n "$MEDIAMTX_VERSION" ]] || { echo "Could not determine latest MediaMTX version"; exit 1; }
fi
TMP=$(mktemp -d)
curl -fsSL -o "$TMP/mtx.tar.gz" \
  "https://github.com/bluenviron/mediamtx/releases/download/${MEDIAMTX_VERSION}/mediamtx_${MEDIAMTX_VERSION}_linux_${ARCH}.tar.gz"
tar -xzf "$TMP/mtx.tar.gz" -C "$TMP"
install -m 0755 "$TMP/mediamtx" /usr/local/bin/mediamtx
rm -rf "$TMP"
echo "    Installed $MEDIAMTX_VERSION"

echo "==> Writing /etc/mediamtx/mediamtx.yml"
LAN_IP=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}')
mkdir -p /etc/mediamtx
if [[ $NO_CAM -eq 1 ]]; then
cat > /etc/mediamtx/mediamtx.yml <<EOF
# Generated by bench-cam-setup.sh (no camera attached yet) - plug it in and re-run the script.
webrtcAdditionalHosts: [${LAN_IP:-127.0.0.1}]

paths:
  ${STREAM_NAME}:
EOF
else
cat > /etc/mediamtx/mediamtx.yml <<EOF
# Generated by bench-cam-setup.sh — edit the script and re-run rather than this file.
webrtcAdditionalHosts: [${LAN_IP:-127.0.0.1}]

paths:
  ${STREAM_NAME}:
    runOnInit: >-
      ffmpeg -hide_banner -loglevel warning
      -f v4l2 -input_format mjpeg -video_size ${WIDTH}x${HEIGHT} -framerate ${FPS} -i ${CAMERA}
      ${ENC} -pix_fmt yuv420p -g $((FPS * 2)) -b:v ${BITRATE} -maxrate ${BITRATE} -bufsize ${BITRATE}
      -an -f rtsp rtsp://localhost:\$RTSP_PORT/\$MTX_PATH
    runOnInitRestart: yes
EOF
fi

echo "==> Creating the service"
id mediamtx >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin mediamtx
usermod -aG video mediamtx
cat > /etc/systemd/system/mediamtx.service <<'EOF'
[Unit]
Description=MediaMTX bench camera stream
After=network-online.target
Wants=network-online.target

[Service]
User=mediamtx
Group=video
ExecStart=/usr/local/bin/mediamtx /etc/mediamtx/mediamtx.yml
Restart=always
RestartSec=3

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable --now mediamtx
systemctl restart mediamtx
sleep 3

if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  echo "==> Opening LAN ports in ufw (RTSP 8554, WebRTC 8889 + 8189/udp)"
  ufw allow 8554/tcp >/dev/null
  ufw allow 8889/tcp >/dev/null
  ufw allow 8189/udp >/dev/null
fi

echo
systemctl --no-pager --lines=8 status mediamtx || true
echo
echo "Done. Open  http://$(hostname).local:8889/${STREAM_NAME}  on your desk computer."
echo "Logs:       journalctl -u mediamtx -f"
if [[ $NO_CAM -eq 1 ]]; then
  echo "No camera yet: plug it in and re-run this script to start streaming."
else
  echo "Lock focus: v4l2-ctl -d ${CAMERA} -l   (then e.g. -c focus_automatic_continuous=0 -c focus_absolute=N)"
fi
